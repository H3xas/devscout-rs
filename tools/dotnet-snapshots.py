#!/usr/bin/env python3
"""Generate and byte-compare the two committed .NET oracle snapshots against one pinned SDK root.

`fixtures/csharp-compiler-facts/compiler-facts.json` and
`fixtures/csharp-context/context.json` record the resolved SDK and MSBuild versions, every
reference assembly's MVID, the hash of every imported file and a fold of all of it into each
compilation's fingerprint. Those values come from the SDK that produced the run, so the same
repository produces different bytes under a different install of the same patch: an installer
layout and a tarball layout of one version ship different reference-assembly bytes and different
workload-manifest content. This tool is the single place that produces those two files, and it
refuses to produce them from anything but a dedicated, declared SDK root -- never whatever
`dotnet` the machine happens to resolve.

Two modes:

  --check   regenerate both snapshots into a disposable directory, compare raw bytes against the
            committed files, and never touch a tracked path. Non-zero exit on drift.
  --write   regenerate and, only after both producers succeeded, replace exactly those two
            committed files.

The pin lives in `tools/dotnet-snapshot-sdk.json`: the SDK version, the official archive for each
supported host with its published SHA-512, and the content inventory of the two input trees whose
bytes reach the snapshots -- the `Microsoft.NETCore.App.Ref` pack the compilations bind against and
the workload manifests the SDK resolves. A root that is missing, carries another or a second SDK,
or whose pack or manifest content differs is refused before any snapshot is generated, so drift is
reported rather than silently baked into committed bytes.

Inventory canonical encoding: the SHA-256 of the byte stream built from every regular file under
the tree, sorted by its root-relative POSIX path, each contributing its UTF-8 path, one NUL byte,
its lowercase-hex SHA-256 and one newline. Symlinks, non-regular files and empty trees are
refusals.

Exit codes: 0 success; 1 a committed snapshot differs from the regenerated bytes; 2 a refused
declaration, root or prerequisite, or a failed child step.

Python 3 standard library only.
"""

import argparse
import hashlib
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import uuid
from pathlib import Path
from typing import NamedTuple

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = REPO_ROOT / "tools" / "dotnet-snapshot-sdk.json"
MANIFEST_VERSION = 1

ORACLE_PROJECT = "tools/scout-semantic"

VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
SHA256_RE = re.compile(r"^sha256:[0-9a-f]{64}$")
SHA512_RE = re.compile(r"^[0-9a-f]{128}$")
LIST_SDKS_RE = re.compile(r"^(\S+)\s+\[(.+)\]$")
MSBUILD_LINE_RE = re.compile(r"^msbuild (\S+) at (.+)$", re.MULTILINE)

# Variables a .NET host exports to point MSBuild and the MSBuild SDK resolver at its own
# installation. They are dropped from every child's environment (see `child_environment`), because
# a host keeps a value it finds already set and would otherwise honour the launcher's selection
# over the root this tool validated.
SDK_SELECTION_VARIABLES = (
    "MSBuildSDKsPath",
    "MSBuildExtensionsPath",
    "MSBuildExtensionsPath32",
    "MSBuildExtensionsPath64",
    "MSBuildUserExtensionsPath",
    "MSBUILD_EXE_PATH",
    "DOTNET_HOST_PATH",
    "DOTNET_MSBUILD_SDK_RESOLVER_SDKS_DIR",
    "DOTNET_MSBUILD_SDK_RESOLVER_SDKS_VER",
    "DOTNET_MSBUILD_SDK_RESOLVER_CLI_DIR",
    "DOTNET_MSBUILD_SDK_RESOLVER_MSBUILD_DIR",
)

# Platform -> runtime identifier, the key the pin's archive table uses. A host outside this table
# has no declared archive and is refused rather than guessed at.
HOST_RIDS = {
    ("darwin", "arm64"): "osx-arm64",
    ("darwin", "x86_64"): "osx-x64",
    ("linux", "x86_64"): "linux-x64",
    ("linux", "aarch64"): "linux-arm64",
}


class Snapshot(NamedTuple):
    key: str
    committed: str
    producer_arguments: tuple


# The two owned snapshots and the exact producer invocation CI has always used for each, so the
# committed bytes and the regeneration path cannot drift apart.
SNAPSHOTS = (
    Snapshot(
        key="compiler-facts",
        committed="fixtures/csharp-compiler-facts/compiler-facts.json",
        producer_arguments=(
            "fixtures/csharp-compiler-facts/Fixture.csproj",
            "--root", "fixtures/csharp-compiler-facts",
            "--emit", "compiler-facts",
            "--tfm", "net9.0", "-p", "Configuration=Debug", "-p", "Platform=AnyCPU",
            "--no-git",
        ),
    ),
    Snapshot(
        key="context",
        committed="fixtures/csharp-context/context.json",
        producer_arguments=(
            "fixtures/csharp-context/Fixture.sln",
            "--root", "fixtures/csharp-context",
            "--emit", "context",
        ),
    ),
)

# Restores the two producers need, per project rather than per solution: the context fixture's own
# solution names a project that deliberately has no file on disk.
RESTORE_TARGETS = (
    ORACLE_PROJECT,
    "fixtures/csharp-compiler-facts/Fixture.csproj",
    "fixtures/csharp-context/src/Clean/Clean.csproj",
    "fixtures/csharp-context/src/Legacy/Legacy.csproj",
    "fixtures/csharp-context/src/Broken/Broken.csproj",
)


class Refusal(Exception):
    """A declaration, root or prerequisite the tool will not act on."""


class DuplicateKey(Exception):
    """A JSON object that declares the same key twice."""


def reject_duplicate_keys(pairs):
    seen = {}
    for key, value in pairs:
        if key in seen:
            raise DuplicateKey(f"the object declares {key!r} twice")
        seen[key] = value
    return seen


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def require_object(value, where):
    if not isinstance(value, dict):
        raise Refusal(f"{where} must be a JSON object")


def require_exact_keys(value, keys, where):
    require_object(value, where)
    missing = sorted(set(keys) - set(value))
    unknown = sorted(set(value) - set(keys))
    if missing:
        raise Refusal(f"{where} is missing {', '.join(missing)}")
    if unknown:
        raise Refusal(f"{where} declares unknown field(s) {', '.join(unknown)}")


def require_digest(value, pattern, where):
    if not isinstance(value, str) or not pattern.match(value):
        raise Refusal(f"{where} is not a digest the pin format allows")


def require_count(value, where):
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise Refusal(f"{where} must be a positive integer")


def load_pin(manifest_path=MANIFEST_PATH):
    try:
        raw = manifest_path.read_text(encoding="utf-8")
    except OSError as error:
        raise Refusal(f"cannot read the pin {manifest_path}: {error}") from error
    try:
        pin = json.loads(raw, object_pairs_hook=reject_duplicate_keys)
    except (ValueError, DuplicateKey) as error:
        raise Refusal(f"the pin {manifest_path} is not readable JSON: {error}") from error

    require_exact_keys(
        pin,
        {"manifestVersion", "sdkVersion", "referencePack", "workloadManifests", "archives"},
        "the pin",
    )
    if pin["manifestVersion"] != MANIFEST_VERSION:
        raise Refusal(
            f"the pin declares manifestVersion {pin['manifestVersion']!r}; this tool reads "
            f"{MANIFEST_VERSION}"
        )
    if not isinstance(pin["sdkVersion"], str) or not VERSION_RE.match(pin["sdkVersion"]):
        raise Refusal("the pin's sdkVersion is not a three-part version")

    require_exact_keys(
        pin["referencePack"],
        {"id", "version", "targetFramework", "fileCount", "treeDigest"},
        "the pin's referencePack",
    )
    for field in ("id", "version", "targetFramework"):
        if not isinstance(pin["referencePack"][field], str) or not pin["referencePack"][field]:
            raise Refusal(f"the pin's referencePack.{field} must be a non-empty string")
    require_count(pin["referencePack"]["fileCount"], "the pin's referencePack.fileCount")
    require_digest(pin["referencePack"]["treeDigest"], SHA256_RE, "the pin's referencePack.treeDigest")

    require_exact_keys(
        pin["workloadManifests"], {"band", "fileCount", "treeDigest"}, "the pin's workloadManifests"
    )
    if not isinstance(pin["workloadManifests"]["band"], str) or not VERSION_RE.match(
        pin["workloadManifests"]["band"]
    ):
        raise Refusal("the pin's workloadManifests.band is not a three-part version")
    require_count(pin["workloadManifests"]["fileCount"], "the pin's workloadManifests.fileCount")
    require_digest(
        pin["workloadManifests"]["treeDigest"], SHA256_RE, "the pin's workloadManifests.treeDigest"
    )

    require_object(pin["archives"], "the pin's archives")
    if not pin["archives"]:
        raise Refusal("the pin's archives table is empty")
    for rid, archive in pin["archives"].items():
        require_exact_keys(archive, {"name", "url", "sha512"}, f"the pin's archives.{rid}")
        if not isinstance(archive["name"], str) or not archive["name"]:
            raise Refusal(f"the pin's archives.{rid}.name is not a usable value")
        if not isinstance(archive["url"], str) or not archive["url"].startswith("http"):
            raise Refusal(f"the pin's archives.{rid}.url is not an absolute URL")
        require_digest(archive["sha512"], SHA512_RE, f"the pin's archives.{rid}.sha512")

    return pin


def host_rid():
    rid = HOST_RIDS.get((sys.platform, platform.machine().lower()))
    if rid is None:
        raise Refusal(
            f"this host ({sys.platform} {platform.machine()}) has no declared snapshot SDK archive"
        )
    return rid


def child_environment(root):
    """The environment every child runs under: this root's host first on PATH, and this root as
    DOTNET_ROOT, so the muxer, the SDK it selects and the MSBuild the oracle registers all come
    from the supplied install rather than an ambient one.

    The variables a .NET host sets to point MSBuild and the MSBuild SDK resolver at its own
    installation are removed from the inherited environment first. A host does not overwrite one it
    already finds, so a child started from a shell or a driven task that inherited another
    installation's selection would build against that installation's targets and tasks while
    `DOTNET_ROOT` and the absolute host path say otherwise."""
    environment = os.environ.copy()
    for variable in SDK_SELECTION_VARIABLES:
        environment.pop(variable, None)
    environment["DOTNET_ROOT"] = str(root)
    environment["DOTNET_MULTILEVEL_LOOKUP"] = "0"
    environment["DOTNET_NOLOGO"] = "1"
    environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1"
    environment["PATH"] = str(root) + os.pathsep + environment.get("PATH", "")
    return environment


def run(command, root, cwd=REPO_ROOT):
    return subprocess.run(
        [str(part) for part in command],
        cwd=str(cwd),
        env=child_environment(root),
        capture_output=True,
        text=True,
    )


def run_step(command, root, label, cwd=REPO_ROOT):
    completed = run(command, root, cwd=cwd)
    if completed.returncode != 0:
        raise Refusal(
            f"{label} failed with exit {completed.returncode}\n"
            f"  command: {' '.join(str(part) for part in command)}\n"
            f"  stderr:\n{completed.stderr.strip()}"
        )
    return completed


def tree_inventory(tree, where):
    if not tree.is_dir():
        raise Refusal(f"{where} is missing at {tree}")
    entries = []
    for dirpath, dirnames, filenames in os.walk(tree, followlinks=False):
        dirnames.sort()
        for name in dirnames:
            child = Path(dirpath) / name
            if child.is_symlink():
                raise Refusal(f"{where} contains a symlinked directory: {child}")
        for name in sorted(filenames):
            full = Path(dirpath) / name
            if full.is_symlink():
                raise Refusal(f"{where} contains a symlink: {full}")
            if not full.is_file():
                raise Refusal(f"{where} contains a non-regular file: {full}")
            entries.append((full.relative_to(tree).as_posix(), sha256_file(full)))
    if not entries:
        raise Refusal(f"{where} is empty at {tree}")
    entries.sort()
    stream = b"".join(
        relative.encode("utf-8") + b"\0" + digest.encode("ascii") + b"\n"
        for relative, digest in entries
    )
    return len(entries), "sha256:" + hashlib.sha256(stream).hexdigest()


def compare_inventory(observed, expected, where):
    observed_count, observed_digest = observed
    if observed_count != expected["fileCount"] or observed_digest != expected["treeDigest"]:
        raise Refusal(
            f"{where} does not match the pin: expected {expected['fileCount']} file(s) with "
            f"{expected['treeDigest']}, found {observed_count} file(s) with {observed_digest}"
        )


def validate_root(root, pin):
    if not root.is_absolute():
        raise Refusal(f"--sdk-root must be an absolute path, got {root}")
    if not root.is_dir():
        raise Refusal(f"--sdk-root is not a directory: {root}")

    host = root / "dotnet"
    if not host.is_file():
        raise Refusal(f"--sdk-root carries no dotnet host at {host}")
    if not os.access(host, os.X_OK):
        raise Refusal(f"the dotnet host at {host} is not executable")

    listed = run_step([host, "--list-sdks"], root, "dotnet --list-sdks")
    found = []
    for line in listed.stdout.splitlines():
        match = LIST_SDKS_RE.match(line.strip())
        if match:
            found.append(match.group(1))
        elif line.strip():
            raise Refusal(f"dotnet --list-sdks printed a line this tool cannot read: {line.strip()}")
    if found != [pin["sdkVersion"]]:
        raise Refusal(
            f"--sdk-root must carry exactly one SDK, {pin['sdkVersion']}; found "
            f"{', '.join(found) if found else 'none'}"
        )

    version = run_step([host, "--version"], root, "dotnet --version").stdout.strip()
    if version != pin["sdkVersion"]:
        raise Refusal(
            f"--sdk-root resolves SDK {version!r} instead of the pinned {pin['sdkVersion']!r}"
        )

    msbuild = run_step([host, "msbuild", "-version", "-nologo"], root, "dotnet msbuild -version")
    if not msbuild.stdout.strip():
        raise Refusal("--sdk-root's dotnet reports no MSBuild version")

    pack = pin["referencePack"]
    compare_inventory(
        tree_inventory(root / "packs" / pack["id"] / pack["version"] / "ref" / pack["targetFramework"],
                       f"the pinned {pack['id']} {pack['version']} {pack['targetFramework']} reference pack"),
        pack,
        "the reference pack",
    )
    manifests = pin["workloadManifests"]
    compare_inventory(
        tree_inventory(root / "sdk-manifests" / manifests["band"], "the pinned workload manifests"),
        manifests,
        "the workload manifests",
    )

    return host


def assert_registered_msbuild(stderr, root, pin, label):
    match = MSBUILD_LINE_RE.search(stderr)
    if match is None:
        raise Refusal(
            f"the {label} run reported no registered MSBuild instance; its stderr was:\n"
            f"{stderr.strip()}"
        )
    version, path = match.group(1), Path(match.group(2))
    if version != pin["sdkVersion"]:
        raise Refusal(f"the {label} run registered MSBuild {version} instead of {pin['sdkVersion']}")
    if not path.is_relative_to(root):
        raise Refusal(f"the {label} run registered MSBuild at {path}, outside {root}")


def generate(root, pin, work):
    host = root / "dotnet"

    for target in RESTORE_TARGETS:
        command = [host, "restore", target]
        if target == ORACLE_PROJECT:
            command.append("--locked-mode")
        run_step(command, root, f"restore of {target}")

    run_step([host, "build", ORACLE_PROJECT, "--no-restore", "-c", "Release"], root, "oracle build")

    produced = {}
    for snapshot in SNAPSHOTS:
        output = work / f"{snapshot.key}.json"
        flag = "--compiler-facts" if snapshot.key == "compiler-facts" else "--context"
        completed = run_step(
            [host, "run", "--project", ORACLE_PROJECT, "--no-build", "-c", "Release", "--",
             *snapshot.producer_arguments, flag, str(output)],
            root,
            f"the {snapshot.key} producer",
        )
        assert_registered_msbuild(completed.stderr, root, pin, snapshot.key)
        if not output.is_file():
            raise Refusal(f"the {snapshot.key} producer wrote nothing to {output}")
        produced[snapshot.key] = output

    for snapshot in SNAPSHOTS:
        text = produced[snapshot.key].read_text(encoding="utf-8")
        for local in (str(root), str(REPO_ROOT)):
            if local in text:
                raise Refusal(
                    f"the regenerated {snapshot.key} snapshot carries the local path {local}"
                )

    return produced


def digest_of(path):
    return "sha256:" + sha256_file(path)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="dotnet-snapshots.py",
        description="Generate and compare the two committed .NET oracle snapshots.",
    )
    parser.add_argument(
        "--sdk-root",
        required=True,
        help="absolute path of the dedicated SDK root the snapshots are generated from",
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="compare without writing a tracked path")
    mode.add_argument("--write", action="store_true", help="replace the two owned snapshots")
    args = parser.parse_args(argv)

    work = REPO_ROOT / "out" / "dotnet-snapshots" / uuid.uuid4().hex
    retain_work = False
    try:
        pin = load_pin()
        host_rid()  # refuse an undeclared host before any child runs
        root = Path(args.sdk_root)
        validate_root(root, pin)
        print(f"snapshot SDK: {pin['sdkVersion']} at {root}")

        work.mkdir(parents=True, exist_ok=True)
        produced = generate(root, pin, work)

        drift = []
        for snapshot in SNAPSHOTS:
            committed = REPO_ROOT / snapshot.committed
            if not committed.is_file():
                raise Refusal(f"the committed {snapshot.key} snapshot is missing at {committed}")
            regenerated = digest_of(produced[snapshot.key])
            current = digest_of(committed)
            state = "ok" if regenerated == current else "drift"
            print(f"{snapshot.key}: committed {current} regenerated {regenerated} {state}")
            if regenerated != current:
                drift.append(snapshot)

        if args.check:
            if drift:
                print(
                    "dotnet-snapshots --check: the committed snapshot(s) "
                    + ", ".join(snapshot.key for snapshot in drift)
                    + " differ from the bytes this SDK root generates",
                    file=sys.stderr,
                )
                return 1
            print("dotnet-snapshots --check: both committed snapshots match")
            return 0

        for snapshot in SNAPSHOTS:
            shutil.copyfile(produced[snapshot.key], REPO_ROOT / snapshot.committed)
        print(f"dotnet-snapshots --write: replaced {len(SNAPSHOTS)} committed snapshot(s)")
        return 0
    except Refusal as refusal:
        retain_work = True
        print(f"dotnet-snapshots: {refusal}", file=sys.stderr)
        return 2
    except Exception as unexpected:  # noqa: BLE001 - an internal failure is a refusal, not drift
        retain_work = True
        print(
            f"dotnet-snapshots: internal failure ({type(unexpected).__name__}): {unexpected}",
            file=sys.stderr,
        )
        return 2
    finally:
        if work.is_dir():
            if retain_work:
                print(f"dotnet-snapshots: kept the disposable output at {work}", file=sys.stderr)
            else:
                shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
